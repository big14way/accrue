#!/usr/bin/env node
// Copies docs/deployments/<label>.json into lib/deployment.json so the console can import it statically.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const label = process.argv[2] ?? process.env.ACCRUE_NETWORK ?? "monad-testnet";
const src = resolve(here, "..", "..", "..", "docs", "deployments", `${label}.json`);
if (!existsSync(src)) {
  console.error(`no deployment at ${src}`);
  process.exit(1);
}
writeFileSync(resolve(here, "..", "lib", "deployment.json"), readFileSync(src));
console.log(`lib/deployment.json ← ${label}`);

// Drill results live in docs/drill at the repo root; copy them inside the app so the drills
// page can render them on hosts that only see apps/console.
import { readdirSync, mkdirSync } from "node:fs";
const drillSrc = resolve(here, "..", "..", "..", "docs", "drill");
const drillDst = resolve(here, "..", "lib", "drill");
mkdirSync(drillDst, { recursive: true });
let n = 0;
if (existsSync(drillSrc)) {
  for (const f of readdirSync(drillSrc)) {
    if (!f.endsWith(".json")) continue;
    writeFileSync(resolve(drillDst, f), readFileSync(resolve(drillSrc, f)));
    n++;
  }
}
// Static index so the page needs no filesystem access at runtime (works on any host).
const files = existsSync(drillSrc) ? readdirSync(drillSrc).filter((f) => f.endsWith(".json")).sort() : [];
const index = files.map((f, i) => `import d${i} from "./${f}";`).join("\n") + `\nexport const drills = [${files.map((_, i) => `d${i}`).join(", ")}] as const;\n`;
writeFileSync(resolve(drillDst, "index.ts"), `// Generated by scripts/sync-deployment.mjs — do not edit.\n${index}`);
console.log(`lib/drill ← ${n} drill result(s)`);
